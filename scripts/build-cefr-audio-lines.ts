/**
 * CEFR-style tests: audio lines and playback map (1.3).
 *
 *   npx tsx scripts/build-cefr-audio-lines.ts          writes scripts/data/cefr-test-lines.json
 *   npx tsx scripts/build-cefr-audio-lines.ts --map    also writes apps/mobile/lib/cefrAudio.ts
 *
 * Record (Git Bash, repo root, ELEVENLABS_API_KEY set):
 *   node scripts/generate-conversation-audio.mjs --lines=scripts/data/cefr-test-lines.json
 * Clips land in apps/mobile/assets/audio/conversations/ as CEFR_*.mp3. Then run this
 * script again with --map, so the app bundles them. (Metro fails on a require() of a
 * missing file, so the map only lists clips that exist.)
 *
 * Voices are consistent within each test: Cécile speaks messages, questions and the
 * examiner; Maxime answers in dialogues; Audrey reads the "Un / Deux / Trois" labels.
 * Old conversation clips are NOT reused: they would put four or five voices in one dialogue.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { CEFR_IDS, CEFR_TESTS } from "../shared/cefrTests";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const CLIPS_DIR = path.join(ROOT, "apps/mobile/assets/audio/conversations");
const CECILE = "Cécile - Interactive Customer Support";
const MAXIME = "Maxime - Dynamic and Natural";
const AUDREY = "Audrey";
const LABELS = new Set(["Un.", "Deux.", "Trois."]);

/** Split a script into spoken turns: "..." separates turns; "Un. Question ? Answer." splits too. */
export function turns(script: string): string[] {
  const out: string[] = [];
  for (let t of script.split("...").map((x) => x.trim()).filter(Boolean)) {
    const lab = t.match(/^(Un|Deux|Trois)\.\s+(.*)$/);
    if (lab) { out.push(`${lab[1]}.`); t = lab[2]; }
    const qa = t.match(/^(.*?\?)\s+(.+)$/);
    if (lab && qa && !t.endsWith("?")) out.push(qa[1], qa[2]);
    else out.push(t);
  }
  return out;
}

type Line = { file: string; level: string; verb: string; tense: string; line: string; french: string; english: string; conversation: string; voice: string };
const lines: Line[] = [];
/** Clip order per test: listening doc id -> files; speaking "P1_1" -> [file]. */
const order: Record<string, Record<string, string[]>> = {};

const add = (id: string, group: string, n: string, french: string, voice: string) => {
  const file = `CEFR_${id}_${group}_${n}.mp3`;
  lines.push({ file, level: `CEFR_${id}`, verb: "", tense: "", line: n, french, english: "", conversation: `CEFR_${id}_${group}`, voice });
  return file;
};

for (const id of CEFR_IDS) {
  const test = CEFR_TESTS[id];
  order[id] = {};
  for (const doc of test.listening) {
    let speaker = 0;
    order[id][doc.id] = turns(doc.script).map((t, i) => {
      let voice: string;
      if (LABELS.has(t)) { voice = AUDREY; speaker = 0; }
      else { voice = speaker % 2 === 0 ? CECILE : MAXIME; speaker++; }
      return add(id, doc.id, String(i + 1).padStart(2, "0"), t, voice);
    });
  }
  for (const part of test.speaking) part.items.forEach((it, i) => {
    order[id][`${part.id}_${i + 1}`] = [add(id, part.id, String(i + 1), (it.say ?? it.prompt).replace(/^«\s*|\s*»$/g, ""), CECILE)];
  });
}

fs.writeFileSync(path.join(ROOT, "scripts/data/cefr-test-lines.json"), JSON.stringify(lines, null, 1) + "\n");
console.log(`${lines.length} clips, ${lines.reduce((n, l) => n + l.french.length, 0)} characters -> scripts/data/cefr-test-lines.json`);

if (process.argv.includes("--map")) {
  const present = lines.filter((l) => fs.existsSync(path.join(CLIPS_DIR, l.file)));
  const missing = lines.length - present.length;
  const ts = `// GENERATED by scripts/build-cefr-audio-lines.ts --map. Do not edit by hand.
// CEFR-style test clips (1.3). ${present.length} of ${lines.length} recorded${missing ? `; ${missing} missing play silent` : ""}.

/** Clip key (file name without .mp3) -> bundled audio. */
export const CEFR_AUDIO: Record<string, number> = {
${present.map((l) => `  ${JSON.stringify(l.file.replace(/\.mp3$/, ""))}: require("../assets/audio/conversations/${l.file}"),`).join("\n")}
};

/** Play order per test: listening document id, or speaking "<partId>_<n>". */
export const CEFR_AUDIO_ORDER: Record<string, Record<string, string[]>> = ${JSON.stringify(
    Object.fromEntries(Object.entries(order).map(([k, v]) => [k, Object.fromEntries(Object.entries(v).map(([g, fs]) => [g, fs.map((f) => f.replace(/\.mp3$/, ""))]))])),
    null, 2)};
`;
  fs.writeFileSync(path.join(ROOT, "apps/mobile/lib/cefrAudio.ts"), ts);
  console.log(`apps/mobile/lib/cefrAudio.ts: ${present.length} clips mapped${missing ? `, ${missing} not recorded yet` : ""}`);
}
