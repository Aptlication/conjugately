#!/usr/bin/env node
// Release 1.2.5 (25 Oct 2026): post-quiz conversations for the 36 Imperfect and
// Pluperfect units of Intermediate A and B.
//
// Source of truth: scripts/data/conversations-125.json (the reviewed dialogues).
// This script writes, from it:
//   apps/mobile/lib/conversations125.ts       the conversations (main + warm-up)
//   scripts/data/conversation-125-lines.json  every app line to record, with a voice
//   apps/mobile/lib/conversation125Audio.ts   require() for every clip that EXISTS
//
// Metro only bundles files named in source, and naming a missing file breaks the
// build, so run this again after recording:
//   ELEVENLABS_API_KEY=… node scripts/generate-conversation-audio.mjs --lines=scripts/data/conversation-125-lines.json
//   node scripts/build-conversations-125.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(here, "..");
const SRC = path.join(here, "data", "conversations-125.json");
const CLIPS = path.join(ROOT, "apps", "mobile", "assets", "audio", "conversations");

const VOICES = ["Audrey", "Voix grand père", "David Vautrin - Tech Narrator", "Maxime - Dynamic and Natural", "Cécile - Interactive Customer Support"];
const TCODE = { Imperfect: "imp", Pluperfect: "pqp" };
const TNAME = { Imperfect: "Imparfait", Pluperfect: "Plus-que-parfait" };
const slug = (v) => v.normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/'/g, "-").replace(/\s+/g, "-").toLowerCase();

const units = JSON.parse(fs.readFileSync(SRC, "utf8"));
const conversations = {};
const warmups = {};
const lines = [];
units.forEach((u, n) => {
  const [, tf, verb] = u.key.split("|");
  const base = `INT_${slug(verb)}_${TCODE[tf]}`;
  const voice = VOICES[n % VOICES.length];
  const app = (t, id) => {
    const file = `${base}_${id}`;
    lines.push({ file: `${file}.mp3`, level: "INT", verb, tense: TNAME[tf], line: String(id), french: t.fr, english: t.en, conversation: base, voice });
    return { who: "app", fr: t.fr, en: t.en, audio: file };
  };
  const you = (t) => ({ who: "you", fr: t.fr, en: t.en, accept: t.accept });
  warmups[u.key] = u.warmup.map((t, i) => (t.who === "app" ? app(t, `w${i + 1}`) : you(t)));
  conversations[u.key] = {
    level: "Intermediate", verb, tense: TNAME[tf],
    turns: u.turns.map((t, i) => (t.who === "app" ? app(t, i + 1) : you(t))),
    newWords: u.newWords,
  };
});

fs.writeFileSync(path.join(ROOT, "apps", "mobile", "lib", "conversations125.ts"),
  `// GENERATED by scripts/build-conversations-125.mjs from scripts/data/conversations-125.json.\n` +
  `// Release 1.2.5: Imperfect and Pluperfect conversations for Intermediate A and B. Do not edit by hand.\n` +
  `import type { Conversation, ConvTurn } from "./conversations";\n\n` +
  `export const CONVERSATIONS_125: Record<string, Conversation> = ${JSON.stringify(conversations, null, 1)};\n\n` +
  `export const WARMUPS_125: Record<string, ConvTurn[]> = ${JSON.stringify(warmups, null, 1)};\n`);
fs.writeFileSync(path.join(here, "data", "conversation-125-lines.json"), JSON.stringify(lines, null, 1) + "\n");

const have = lines.filter((l) => fs.existsSync(path.join(CLIPS, l.file)) && fs.statSync(path.join(CLIPS, l.file)).size > 1000);
const body = have.map((l) => `  ${JSON.stringify(l.file.replace(/\.mp3$/, ""))}: require("../assets/audio/conversations/${l.file}"),`).join("\n");
fs.writeFileSync(path.join(ROOT, "apps", "mobile", "lib", "conversation125Audio.ts"),
  `// GENERATED by scripts/build-conversations-125.mjs — lists only the 1.2.5 conversation\n` +
  `// clips that exist in assets/audio/conversations. Re-run it after recording.\n` +
  `export const AUDIO_125: Record<string, number> = {\n${body}${body ? "\n" : ""}};\n`);
console.log(`${units.length} conversations, ${lines.length} app lines; clips bundled: ${have.length} of ${lines.length}`);
