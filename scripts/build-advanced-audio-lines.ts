/**
 * Advanced A (pilot): audio lines and playback map.
 *
 *   npx tsx scripts/build-advanced-audio-lines.ts          writes scripts/data/advanced-lines.json
 *   npx tsx scripts/build-advanced-audio-lines.ts --map    also writes apps/mobile/lib/advancedAudio.ts
 *
 * Record (Git Bash, repo root, ELEVENLABS_API_KEY set):
 *   node scripts/generate-conversation-audio.mjs --lines=scripts/data/advanced-lines.json
 * Clips land in apps/mobile/assets/audio/conversations/ as ADV_*.mp3 and ADVW_*.mp3.
 * Then run this script again with --map, so the app bundles them. (Metro fails on a
 * require() of a missing file, so the map only lists clips that exist; a missing
 * clip just stays silent in the app.)
 *
 * Voices: the articles alternate Cécile (odd units) and Maxime (even units), as the
 * plan says; Cécile asks every question and says every stock line, since she runs
 * the conversation and reads each verb-quiz answer; every word card is read by Cécile.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { ADVANCED_PHRASES, ADVANCED_UNITS, lexFor } from "../shared/advanced/content";
import { keysIn } from "../shared/advanced/tokenize";
import { STOCK_LINES, articleClip, convClip, quizClip, spokenHeadword, wordClip } from "../shared/advanced/audioKeys";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const CLIPS_DIR = path.join(ROOT, "apps/mobile/assets/audio/conversations");
const CECILE = "Cécile - Interactive Customer Support";
const MAXIME = "Maxime - Dynamic and Natural";

type Line = { file: string; voice: string; french: string };
const lines: Line[] = [];
const seen = new Set<string>();
const add = (key: string, voice: string, french: string) => {
  if (seen.has(key)) return;
  seen.add(key);
  lines.push({ file: `${key}.mp3`, voice, french });
};

for (const [k, t] of Object.entries(STOCK_LINES)) add(k, CECILE, t);
for (const [n, u] of ADVANCED_UNITS.entries()) {
  add(articleClip(u.id), n % 2 === 0 ? CECILE : MAXIME, u.text);
  // Cécile's conversation lines (the learner's replies are theirs to say).
  u.conversation.turns.forEach((t, i) => { if (t.who === "app") add(convClip(u.id, i), CECILE, t.fr); });
  // The verb quiz's correct French, played after each answer.
  u.quiz.forEach((q, i) => add(quizClip(u.id, i), CECILE, q.answer));
}
// Words: every headword a tap can show, plus the key words.
for (const u of ADVANCED_UNITS) {
  for (const key of keysIn(u.text, ADVANCED_PHRASES)) {
    const e = lexFor(u.id, key);
    if (e) add(wordClip(e.fr), CECILE, spokenHeadword(e.fr));
  }
  for (const w of u.keyWords) add(wordClip(w.fr), CECILE, spokenHeadword(w.fr));
}

fs.writeFileSync(path.join(ROOT, "scripts/data/advanced-lines.json"), JSON.stringify(lines, null, 1) + "\n");
const chars = lines.reduce((n, l) => n + l.french.length, 0);
console.log(`advanced-lines.json: ${lines.length} clips, ${chars} characters`);

if (process.argv.includes("--map")) {
  const have = lines.filter((l) => fs.existsSync(path.join(CLIPS_DIR, l.file)));
  const body = have.map((l) => `  "${l.file.replace(/\.mp3$/, "")}": require("../assets/audio/conversations/${l.file}"),`).join("\n");
  const ts = `// GENERATED by scripts/build-advanced-audio-lines.ts --map. Do not edit by hand.
// Advanced A clips. ${have.length} of ${lines.length} recorded.

/** Clip key (file name without .mp3) -> bundled audio. */
export const ADVANCED_AUDIO: Record<string, number> = {
${body}
};
`;
  fs.writeFileSync(path.join(ROOT, "apps/mobile/lib/advancedAudio.ts"), ts);
  console.log(`advancedAudio.ts: ${have.length} of ${lines.length} clips bundled`);
}
