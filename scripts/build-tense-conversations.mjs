#!/usr/bin/env node
// Tense Conversations (plan of 31 Oct 2026, docs: tense-conversations-and-journey-plan).
// One longer conversation at the end of each tense, weaving every verb of the tense.
//
// Source of truth: scripts/data/tense-conversations.json (reviewed scripts).
// Check it first:  npx tsx scripts/audit-tense-conversations.ts
// This script writes, from it:
//   apps/mobile/lib/conversationsTense.ts        the conversations
//   scripts/data/tense-conversation-lines.json   every app line to record, with its voice
//   apps/mobile/lib/conversationTenseAudio.ts    require() for every clip that EXISTS
//
// Metro only bundles files named in source, and naming a missing file breaks the
// build, so run this again after recording:
//   ELEVENLABS_API_KEY=… node scripts/generate-conversation-audio.mjs --lines=scripts/data/tense-conversation-lines.json
//   node scripts/build-tense-conversations.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(here, "..");
const SRC = path.join(here, "data", "tense-conversations.json");
const CLIPS = path.join(ROOT, "apps", "mobile", "assets", "audio", "conversations");

const LCODE = { Beginner: "BEG", Novice: "NOV", Elementary: "ELE", "Intermediate A": "INTA", "Intermediate B": "INTB" };
const TCODE = { Present: "pres", Past: "pc", Future: "fut", Imperfect: "imp", Pluperfect: "pqp" };
const TNAME = { Present: "Présent", Past: "Passé composé", Future: "Futur simple", Imperfect: "Imparfait", Pluperfect: "Plus-que-parfait" };

const data = JSON.parse(fs.readFileSync(SRC, "utf8"));
const out = {};
const lines = [];
for (const [key, c] of Object.entries(data)) {
  const [level, tf] = key.split("|");
  const base = `TC_${LCODE[level]}_${TCODE[tf]}`;
  out[key] = {
    level, timeFrame: tf, tense: TNAME[tf], title: c.title, titleEn: c.titleEn,
    character: c.character, scene: c.scene, verbs: c.verbs, newWords: c.newWords,
    turns: c.turns.map((t, i) => {
      if (t.who === "app") {
        const file = `${base}_${i + 1}`;
        lines.push({ file: `${file}.mp3`, level: LCODE[level], verb: "*", tense: TNAME[tf], line: String(i + 1),
          french: t.fr, english: t.en, conversation: base, voice: c.voice });
        return { who: "app", fr: t.fr, en: t.en, audio: file };
      }
      return { who: "you", fr: t.fr, en: t.en, accept: t.accept, verb: t.verb, person: t.person,
        ...(t.callback ? { callback: t.callback } : {}), options: t.options };
    }),
  };
}

fs.writeFileSync(path.join(ROOT, "apps", "mobile", "lib", "conversationsTense.ts"),
  `// GENERATED by scripts/build-tense-conversations.mjs from scripts/data/tense-conversations.json.\n` +
  `// Tense Conversations (31 Oct 2026). Do not edit by hand.\n` +
  `import type { ConvTurn } from "./conversations";\n\n` +
  `export type TenseTurn = ConvTurn & { verb?: string; person?: string; callback?: string; options?: string[] };\n\n` +
  `export type TenseConversation = {\n  level: string; timeFrame: string; tense: string; title: string; titleEn: string;\n` +
  `  character: string; scene: string; verbs: string[]; newWords: { fr: string; en: string }[]; turns: TenseTurn[];\n};\n\n` +
  `export const TENSE_CONVERSATIONS: Record<string, TenseConversation> = ${JSON.stringify(out, null, 1)};\n`);
fs.writeFileSync(path.join(here, "data", "tense-conversation-lines.json"), JSON.stringify(lines, null, 1) + "\n");

const have = lines.filter((l) => fs.existsSync(path.join(CLIPS, l.file)) && fs.statSync(path.join(CLIPS, l.file)).size > 1000);
const body = have.map((l) => `  ${JSON.stringify(l.file.replace(/\.mp3$/, ""))}: require("../assets/audio/conversations/${l.file}"),`).join("\n");
fs.writeFileSync(path.join(ROOT, "apps", "mobile", "lib", "conversationTenseAudio.ts"),
  `// GENERATED by scripts/build-tense-conversations.mjs — lists only the Tense Conversation\n` +
  `// clips that exist in assets/audio/conversations. Re-run it after recording.\n` +
  `export const AUDIO_TENSE: Record<string, number> = {\n${body}${body ? "\n" : ""}};\n`);
console.log(`${Object.keys(out).length} tense conversations, ${lines.length} app lines; clips bundled: ${have.length} of ${lines.length}`);
