#!/usr/bin/env node
// Builds shared/advanced/content.ts from the Advanced source data:
//   scripts/data/advanced-theme1.json   the articles, key words and questions
//   scripts/data/advanced-lexicon.json  a gloss for every word, the set phrases,
//                                       and per-unit overrides for words that
//                                       mean something else in one article
// Usage: node scripts/build-advanced-data.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const read = (f) => JSON.parse(fs.readFileSync(path.join(here, "data", f), "utf8"));
const theme1 = read("advanced-theme1.json");
const lex = read("advanced-lexicon.json");

const themes = [{
  id: theme1.theme, title: theme1.themeTitle, titleEn: "Everyday life", level: theme1.level,
  units: theme1.units.map(({ id, title, titleEn, strand, grammar, text, textEn, keyWords, questions }) =>
    ({ id, title, titleEn, strand, grammar, text, textEn, keyWords, questions })),
}];

const j = (x) => JSON.stringify(x, null, 1);
const out = `// GENERATED by scripts/build-advanced-data.mjs. Do not edit by hand:
// edit scripts/data/advanced-*.json and run the script again.
import type { AdvTheme, AdvUnit, LexEntry } from "./types";
import { phraseKey, wordKey } from "./tokenize";

export const ADVANCED_THEMES: AdvTheme[] = ${j(themes)};

/** Every word in every article, keyed by its lowercase surface form. */
const WORDS: Record<string, LexEntry> = ${j(lex.words)};

/** Set phrases: saved and glossed as one piece. */
const PHRASE_LIST: { words: string[]; entry: LexEntry }[] = ${j(lex.phrases)};

/** A word that means something else in one article: unit id -> key -> entry. */
const OVERRIDES: Record<string, Record<string, LexEntry>> = ${j(lex.overrides)};

export const ADVANCED_PHRASES: string[][] = PHRASE_LIST.map((p) => p.words);
const PHRASES: Record<string, LexEntry> = Object.fromEntries(PHRASE_LIST.map((p) => [phraseKey(p.words), p.entry]));

export const ADVANCED_UNITS: AdvUnit[] = ADVANCED_THEMES.flatMap((t) => t.units);

export function advancedUnit(id: string): AdvUnit | undefined {
  return ADVANCED_UNITS.find((u) => u.id === id);
}

/** The gloss for a tapped piece of an article. */
export function lexFor(unitId: string, key: string): LexEntry | undefined {
  return OVERRIDES[unitId]?.[key] ?? PHRASES[key] ?? WORDS[key] ?? WORDS[wordKey(key)];
}

/** For the vocab test's wrong answers: content words with a picture clue or a gloss. */
export const LEXICON_POOL: LexEntry[] = [...Object.values(WORDS), ...Object.values(PHRASES)];
`;
fs.writeFileSync(path.join(here, "..", "shared", "advanced", "content.ts"), out);
console.log(`content.ts: ${themes[0].units.length} units, ${Object.keys(lex.words).length} words, ${lex.phrases.length} phrases`);
