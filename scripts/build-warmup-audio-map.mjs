#!/usr/bin/env node
// Writes apps/mobile/lib/conversationWarmupAudio.ts: a static require() for every
// 1.2.3 warm-up clip that exists. Metro only bundles files named in the source,
// and naming a file that doesn't exist breaks the build, so this lists only what
// has been recorded. Run after generate-conversation-audio.mjs --lines=…warmup…
//   node scripts/build-warmup-audio-map.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const lines = JSON.parse(fs.readFileSync(path.join(here, "data", "conversation-warmup-lines.json"), "utf8"));
const dir = path.join(here, "..", "apps", "mobile", "assets", "audio", "conversations");
const have = lines.filter((l) => fs.existsSync(path.join(dir, l.file)) && fs.statSync(path.join(dir, l.file)).size > 1000);
const missing = lines.filter((l) => !have.includes(l)).map((l) => l.file);
const body = have
  .map((l) => `  ${JSON.stringify(l.file.replace(/\.mp3$/, ""))}: require("../assets/audio/conversations/${l.file}"),`)
  .join("\n");
fs.writeFileSync(path.join(here, "..", "apps", "mobile", "lib", "conversationWarmupAudio.ts"),
  `// GENERATED by scripts/build-warmup-audio-map.mjs — lists only the warm-up clips\n` +
  `// that exist in assets/audio/conversations. Re-run it after recording.\n` +
  `export const WARMUP_AUDIO: Record<string, number> = {\n${body}${body ? "\n" : ""}};\n`);
console.log(`Warm-up clips bundled: ${have.length} of ${lines.length}`);
if (missing.length) console.log(`Not recorded yet (they will play silently): ${missing.join(", ")}`);
